import { readFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

// Runs inside the isolated inbox database after its existing feature checks.
export async function testPrivateSections({ db, owner, user, grant, staff, admin, contact }) {
  await owner();
  await db.exec(`
    alter table storage.buckets add column allowed_mime_types text[];
    create function set_updated_at() returns trigger language plpgsql as $$ begin new.updated_at=now(); return new; end $$;
    create table bookings(id uuid primary key default gen_random_uuid(),name text);
    create table employee_tasks(id uuid primary key default gen_random_uuid(),employee_id uuid,contact_id uuid,title text,due_date date,is_done boolean);
    alter table contacts add column status text;
    alter table pipeline_stages add column sort_order int not null default 0;
    alter table form_submissions add column attachments jsonb default '[]';
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/20260926140000_client_documents.sql',import.meta.url),'utf8'));
  for (const table of ['contacts','bookings','employee_tasks','form_submissions','newsletter_subscribers','stage_task_templates']) {
    await db.exec(`alter table public.${table} enable row level security;
      grant select,insert,update,delete on public.${table} to authenticated;
      create policy phase3_team_select on public.${table} for select to authenticated using(is_team());
      create policy phase3_team_insert on public.${table} for insert to authenticated with check(is_team());
      create policy phase3_team_update on public.${table} for update to authenticated using(is_team()) with check(is_team());
      create policy phase3_admin_delete on public.${table} for delete to authenticated using(is_admin());`);
  }
  await db.exec(`
    create policy phase3_legacy_open on contacts for all to authenticated using(true) with check(true);
    alter table email_outbox enable row level security;
    grant select on email_outbox to authenticated;
    create policy phase3_outbox_read on email_outbox for select to authenticated using(is_team());
    grant select,insert,update,delete on client_documents,team_resources to authenticated;
    alter table storage.objects enable row level security;
    grant select,insert,update,delete on storage.objects to authenticated,anon;
    create policy phase3_form_read on storage.objects for select to authenticated using(bucket_id='form-attachments' and is_team());
    create policy phase3_public_form_upload on storage.objects for insert to anon,authenticated with check(bucket_id='form-attachments');
    alter table cms_versions enable row level security;
    grant select on cms_versions to authenticated;
  `);
  await db.exec(await readFile(new URL('../supabase/migrations/20261004110000_enforce_private_section_access.sql',import.meta.url),'utf8'));
  await db.query("insert into client_documents(contact_id,file_name,storage_path) values($1,'private.pdf','privacy/client.pdf')",[contact]);
  await db.exec(`insert into team_resources(title,file_name,storage_path) values('Internal','internal.pdf','privacy/team.pdf');
    insert into bookings(name) values('Private meeting'); insert into employee_tasks(title) values('Private task');
    insert into storage.objects(bucket_id,name) values('client-documents','privacy/client.pdf'),('team-resources','privacy/team.pdf'),('form-attachments','privacy/form.pdf');`);
  const hiddenTables=['contacts','bookings','form_submissions','newsletter_subscribers','employee_tasks','stage_task_templates','client_documents','team_resources','email_outbox','client_tags','contact_tags'];
  const asStaff = async sections => { await owner(); await grant(staff,sections); await user(staff); };
  const count = async sql => (await db.query(sql)).rows.length;
  await asStaff({news:true});
  for (const table of hiddenTables) assert.equal(await count(`select * from ${table}`),0,table+' hidden from unrelated staff');
  assert.equal(await count("select * from storage.objects where name like 'privacy/%'"),0);
  assert.ok((await db.query('select * from employees')).rows.every(e=>e.user_id===staff),'own access record only');
  assert.equal((await db.query("update contacts set name='Intrusion' where id=$1 returning id",[contact])).rows.length,0);
  assert.equal((await db.query('delete from contacts where id=$1 returning id',[contact])).rows.length,0,'legacy allow-all cannot bypass DELETE');
  await assert.rejects(db.query("insert into contacts(id,name) values(gen_random_uuid(),'Intrusion')"),/row-level security/);
  await assert.rejects(db.query("insert into storage.objects(bucket_id,name) values('client-documents','privacy/injected.pdf')"),/row-level security/);
  await asStaff({clients:true});
  assert.ok(await count('select * from contacts'));
  await db.query("update contacts set name='Authorized edit' where id=$1",[contact]);
  assert.equal((await db.query('delete from contacts where id=$1 returning id',[contact])).rows.length,0,'legacy permissive policy cannot grant non-admin deletion');
  assert.equal(await count('select * from client_documents'),0,'Clients alone cannot read documents');
  assert.equal(await count('select * from email_outbox'),0,'Clients alone cannot read email logs');
  await asStaff({documents:true});
  assert.ok(await count('select * from contacts'),'Documents retains client picker');
  assert.equal(await count('select * from client_documents'),1);
  assert.equal(await count('select * from team_resources'),1);
  assert.equal(await count("select * from storage.objects where name like 'privacy/%'"),3);
  await db.query("update client_documents set note='Checked' where storage_path='privacy/client.pdf'");
  assert.equal(await count('delete from client_documents returning id'),0,'document deletion stays admin-only');
  assert.equal((await db.query("update contacts set name='Denied' where id=$1 returning id",[contact])).rows.length,0,'picker does not grant CRM writes');
  await asStaff({'form-emails':true});
  assert.ok(await count('select * from email_outbox'),'Form Emails retains logs');
  assert.equal(await count('select * from client_documents'),0);
  await asStaff({forms:true});
  assert.ok(await count('select * from form_submissions'));
  assert.equal(await count("select * from storage.objects where name like 'privacy/%'"),1,'Forms reads submitted attachments only');
  await asStaff({pipeline:true});
  assert.ok(await count('select * from contacts'));
  assert.ok(await count('select * from employee_tasks'));
  await asStaff({settings:true});
  assert.equal(await count('select * from contacts'),0);
  await owner();
  // Actual stage-transition trigger must still create tasks through the new RLS.
  await db.exec(`create trigger phase3_stage_tasks after update of status on contacts for each row execute function fn_auto_assign_stage_tasks();
    insert into stage_task_templates(stage,title) values('Security Done','Follow up');`);
  const assigned=(await db.query('select id from employees where user_id=$1',[staff])).rows[0].id;
  await db.query('update contacts set assigned_employee_id=$1 where id=$2',[assigned,contact]);
  await db.exec("insert into pipeline_stages(name,sort_order) values('Security New',0),('Security Done',1); update contacts set status='Security New'");
  const stages=(await db.query('select id,name,sort_order from pipeline_stages order by sort_order,id')).rows;
  await user(staff);
  await db.query('select configure_pipeline_stages($1,$2)',[JSON.stringify(stages),JSON.stringify(stages.map((r,i)=>({...r,name:i===0?'Security Renamed':r.name})))]);
  await owner();
  assert.equal((await db.query('select status from contacts where id=$1',[contact])).rows[0].status,'Security Renamed');
  await asStaff({pipeline:true});
  await db.query("update contacts set status='Security Done' where id=$1",[contact]);
  assert.ok(await count("select * from employee_tasks where title like 'Follow up%'") > 0,'stage transition still assigns a task');
  await owner();
  const news=(await db.query("insert into cms_documents(kind,title) values('news_article','News draft') returning id")).rows[0].id;
  const page=(await db.query("insert into cms_documents(kind,title) values('page','Private page draft') returning id")).rows[0].id;
  await db.query("insert into cms_versions(document_id,title) values($1,'News history'),($2,'Page history')",[news,page]);
  await asStaff({news:true});
  assert.equal((await db.query('select id from cms_documents where id=$1',[page])).rows.length,0);
  assert.equal((await db.query('select id from cms_versions where document_id=$1',[page])).rows.length,0);
  assert.equal((await db.query('select id from cms_versions where document_id=$1',[news])).rows.length,1);
  await assert.rejects(db.query('select configure_pipeline_stages($1,$2)',[JSON.stringify(stages),JSON.stringify(stages)]),/Only admins/);
  await owner();
  await db.exec("create policy phase3_legacy_storage_read on storage.objects for select to anon using(true)");
  await db.exec('set role anon');
  await assert.rejects(db.query('select * from contacts'),/permission denied/);
  await db.query("insert into storage.objects(bucket_id,name) values('form-attachments','privacy/public-form.pdf')");
  assert.equal(await count("select * from storage.objects where name like 'privacy/%'"),0);
  await user(admin);
  assert.equal(await count("delete from client_documents where storage_path='privacy/client.pdf' returning id"),1);
  console.log('Section checks passed: direct API reads/writes, known IDs, legacy OR policy, private storage, public forms, and Settings stage renames.');
}
